"""Differential tests for set_key / get_key / unset_key sequences (channel 4).

Each scenario applies a sequence of edits to a starting file (absent, empty,
duplicate keys, CRLF, comments/export, quoted) and compares the return values,
log records, raised errors, the resulting directory (names, types, permission
bits, symlink targets, exact bytes), and whether the target's inode changed.
"""

from __future__ import annotations

import os

import diff_helpers
import grammar
from hypothesis import HealthCheck, given, settings

_SCALE = int(os.environ.get("ENVRELAY_SCALE", "300"))

_COMMON = dict(
    deadline=None,
    suppress_health_check=[HealthCheck.too_slow, HealthCheck.data_too_large],
)


@settings(max_examples=_SCALE * 6, **_COMMON)
@given(scenario=grammar.edit_scenario())
def test_edit_sequences(scenario):
    initial, ops, make_symlink = scenario
    ok, summaries = diff_helpers.compare_edit_sequence(
        initial, ops, make_symlink=make_symlink
    )
    assert ok, "edit mismatch: initial=%r ops=%r symlink=%s\n mine=%r\n ora =%r" % (
        initial,
        ops,
        make_symlink,
        summaries["mine"],
        summaries["ora"],
    )


@settings(max_examples=_SCALE * 6, **_COMMON)
@given(text=grammar.env_documents())
def test_edit_every_key_of_generated_file(text):
    """Start from a document generated by the parsing grammar (blank lines,
    whitespace-only lines, comments, bare keys in every position) and run set_key
    and unset_key on every key it contains, plus a key it doesn't, so the
    blank-line-above-key behavior is exercised across the whole grammar."""
    import envrelay

    initial = text.encode("utf-8", "surrogatepass")
    import io as _io

    keys = list(envrelay.dotenv_values(stream=_io.StringIO(text)).keys())
    keys = keys + ["ABSENT_KEY"]
    for key in keys[:6]:
        for op in (
            ("set_key", key, "x", "always", False, "utf-8", False),
            ("unset_key", key, "always", "utf-8", False),
        ):
            ok, summaries = diff_helpers.compare_edit_sequence(initial, [op])
            assert ok, "edit-every-key mismatch: text=%r op=%r\n mine=%r\n ora=%r" % (
                text,
                op,
                summaries["mine"],
                summaries["ora"],
            )
